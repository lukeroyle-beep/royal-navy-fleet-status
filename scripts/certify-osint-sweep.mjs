import fs from 'node:fs';
import path from 'node:path';
import { validateCertificateCandidate } from './lib/sweep-validation.mjs';
import { execFileSync } from 'node:child_process';
import { digest } from './lib/acquisition.mjs';
import { resolvePrivateInputs } from './lib/private-inputs.mjs';
import { atomicJson } from './lib/acquisition.mjs';
import { reconcileFleet } from './lib/sweep-analysis.mjs';
import { buildSweepCertificate } from './lib/sweep-certificate.mjs';
const arg = name => process.argv.find(a=>a.startsWith(`--${name}=`))?.slice(name.length+3);
const inputs = resolvePrivateInputs();
if (inputs.mode !== 'external') throw new Error('Certification requires external private inputs');
const read = file => JSON.parse(fs.readFileSync(file,'utf8'));
const run = read(arg('run'));
if (run.sweepCertificate?.status === 'PASS') throw new Error('Certificate already sealed; do not rewrite');
const runFile = fs.realpathSync(arg('run'));
const relative = path.relative(inputs.root, runFile);
if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('Certificate run must be in canonical external private inputs');
const validation = validateCertificateCandidate({ entities:inputs.readJson('vessels'), registry:inputs.readJson('sources'), evidenceLog:inputs.readJson('evidence'), assessmentLog:inputs.readJson('assessments'), run });
const testEnvironment = { ...process.env };
delete testEnvironment.RNFS_PRIVATE_DATA_ROOT;
delete testEnvironment.RNFS_PRIVATE_DATA_FIXTURE;
const testOutput = execFileSync('npm', ['test'], { cwd: new URL('..', import.meta.url), env:testEnvironment, encoding:'utf8', maxBuffer:10000000 });
validation.tests = { pass:true, artifactHash:digest(testOutput), command:'npm test (legacy and synthetic regression inputs)', completedAt:new Date().toISOString() };
const at = new Date().toISOString();
const reconciliation = reconcileFleet({ entities:inputs.readJson('vessels'), assessmentLog:inputs.readJson('assessments'), evidenceItems:inputs.readJson('evidence').evidence, run, at });
run.certificateInputs = { acquisition:read(arg('acquisition')), adjudication:read(arg('adjudication')), validation, reconciliation, registeredSources:inputs.readJson('sources').sources.length };
run.sweepCertificate = buildSweepCertificate({ run, ...run.certificateInputs, at });
atomicJson(arg('run'),run);
console.log(JSON.stringify(run.sweepCertificate,null,2));
if (run.sweepCertificate.status !== 'PASS') process.exitCode=1;
